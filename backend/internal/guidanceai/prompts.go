func educationLevelFromAnswers(userInput, answers string) string {
	if intent := intentFromContext(userInput, answers); intent != "" {
		return intent
	}

	lower := strings.ToLower(userInput + "\n" + answers)
	switch {
	case hasUniversityIntent(lower):
		return universitySelectionGuidance()
	case strings.Contains(lower, "12 клас"), strings.Contains(lower, "12-ти"), strings.Contains(lower, "завършил"):
		return universitySelectionGuidance()
	case strings.Contains(lower, "11 клас"), strings.Contains(lower, "10 клас"):
		return `ОБРАЗОВАТЕЛНО НИВО: 10–11 клас.
items[] = подготовка за ДЗИ + гимназии/ПГ (ако още не е избрал) + ранно кандидатстване за ВУ.`
	case strings.Contains(lower, "7 клас"), strings.Contains(lower, "7-ми"), strings.Contains(lower, "vii клас"):
		return highSchoolSelectionGuidance()
	case strings.Contains(lower, "8 клас"), strings.Contains(lower, "9 клас"):
		return `ОБРАЗОВАТЕЛНО НИВО: 8–9 клас (вече в гимназия).
items[] = по-силна гимназия/профил, подготовка за ДЗИ — НЕ университети като основен път.`
	default:
		return `Определи нивото от текста. Ако родител с дете 13–14 г. търси гимназия — items[] = само гимназии/ПГ.`
	}
}

