func intentFromContext(userInput, answers string) string {
	combined := strings.ToLower(userInput + "\n" + answers)

	if hasUniversityIntent(combined) {
		return universitySelectionGuidance()
	}

	gymnasiumIntent := strings.Contains(combined, "гимназ") ||
		strings.Contains(combined, "high school") ||
		strings.Contains(combined, "след 7") ||
		strings.Contains(combined, "след седми") ||
		strings.Contains(combined, "viii клас") ||
		strings.Contains(combined, "viii") ||
		(strings.Contains(combined, "прием") && strings.Contains(combined, "7")) ||
		strings.Contains(combined, "матура") ||
		strings.Contains(combined, "нво")

	in7thClass := strings.Contains(combined, "7 клас") ||
		strings.Contains(combined, "7-ми") ||
		strings.Contains(combined, "vii клас") ||
		strings.Contains(combined, "седми клас")

	if gymnasiumIntent || (in7thClass && !hasUniversityIntent(combined) && (strings.Contains(combined, "python") || strings.Contains(combined, "програмир") || strings.Contains(combined, "робот"))) {
		return highSchoolSelectionGuidance()
	}
	return ""
}

