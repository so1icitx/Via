// LangInstruction returns language guidance for model prompts.
func LangInstruction(lang string, allCaps bool) string {
	if lang == "en" {
		if allCaps {
			return "Write ALL text content in natural, correct English."
		}
		return "Write everything (questions and options) in natural, correct English."
	}
	if allCaps {
		return "Пиши ЦЯЛОТО текстово съдържание на естествен, правилен български език."
	}
	return "Пиши всичко (въпроси и опции) на естествен, правилен български език."
}

